        long: functions.latlongString(currentUserLocationValue!, false),
      );

      if ((_model.locationResp?.succeeded ?? true)) {
        _model.location = GeoCodeReverseCall.location(
          (_model.locationResp?.jsonBody ?? ''),
        )!;
        safeSetState(() {});
      }
      _model.activityResp = await queryQuestionRecordOnce(
        queryBuilder: (questionRecord) => questionRecord.where(
          'questionCategory',
          isEqualTo: 'Activity',
        ),
        singleRecord: true,
      ).then((s) => s.firstOrNull);
      _model.foodResp = await queryQuestionRecordOnce(
        queryBuilder: (questionRecord) => questionRecord.where(
          'questionCategory',
          isEqualTo: 'Food',
        ),
        singleRecord: true,
      ).then((s) => s.firstOrNull);
      _model.movieResp = await queryQuestionRecordOnce(
        queryBuilder: (questionRecord) => questionRecord.where(
          'questionCategory',
          isEqualTo: 'Movie',
        ),
        singleRecord: true,
      ).then((s) => s.firstOrNull);
      if (_model.activityResp?.reference.id != null &&
          _model.activityResp?.reference.id != '') {
        FFAppState().fetchedActivityQuestions = functions
            .retrieveRandomQuestionFromList(
                _model.activityResp?.question?.toList())
            .toList()
            .cast<QuestionStruct>();
        FFAppState().fetchedFoodQuestions = functions
            .retrieveRandomQuestionFromList(_model.foodResp?.question?.toList())
            .toList()
            .cast<QuestionStruct>();
        FFAppState().fetchedMovieQuestions = functions
            .retrieveRandomQuestionFromList(
                _model.movieResp?.question?.toList())
            .toList()
            .cast<QuestionStruct>();
        safeSetState(() {});
      }
    });

    getCurrentUserLocation(defaultLocation: LatLng(0.0, 0.0), cached: true)
        .then((loc) => safeSetState(() => currentUserLocationValue = loc));
